TEMPLATE_SRC = ["strings.xml", "strings_cs14.xml", "strings_cs15.xml", "strings_manager.xml",
                "strings_create_instance.xml", "strings_profile_picker.xml"]

def main(res_dir):
    src = {}
    for f in TEMPLATE_SRC:
        p = os.path.join(res_dir, "values", f)
        if not os.path.exists(p): continue
        s = open(p, encoding="utf-8").read()
        for name, attrs, text in re.findall(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', s, re.S):
            src[name] = (attrs, text)
    missing = [k for k in T if k not in src]
    if missing:
        print("UNKNOWN KEYS:", missing); sys.exit(1)
    fmt = re.compile(r'%(\d+\$)?[sdf.0-9]*[sdf%]')
    for k, v in T.items():
        a = sorted(fmt.findall(src[k][1])); b = sorted(fmt.findall(v))
        if a != b:
            print("FORMAT MISMATCH", k, src[k][1], "=>", v); sys.exit(1)
        if "translatable=\"false\"" in src[k][0]:
            print("NOT TRANSLATABLE", k); sys.exit(1)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Hinglish: Hindi written with Latin letters. Generated by tools/hinglish.py -->',
           '<resources>']
    for k, v in T.items():
        # escape bare apostrophes (keep already escaped ones)
        v = re.sub(r"(?<!\\)'", r"\\'", v)
        out.append(f'    <string name="{k}">{v}</string>')
    out.append('</resources>')
    d = os.path.join(res_dir, "values-b+hi+Latn")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "strings.xml"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("written", len(T), "strings")

if __name__ == "__main__":
    main(sys.argv[1])
